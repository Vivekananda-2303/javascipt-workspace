//while
let index=0

while(index<10){
    console.log(`Value of index is ${index}`);
    index++;
}
let myArray=['flash','batman','superman','wonderwomen'];
let arr=0;
while(arr<myArray.length){
    console.log(`Value is ${myArray[arr]}`);
    arr=arr+1;
}
//do-while loop
let score=1;
do{
    console.log(`Value of score is ${score}`);
    score++;
} while(score<=10);